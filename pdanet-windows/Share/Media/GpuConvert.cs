using SharpGen.Runtime;
using Vortice.Direct3D;
using Vortice.Direct3D11;
using Vortice.DXGI;
using Vortice.Mathematics;

namespace PdaNetPortable.Share.Media;

/// <summary>
/// Turns the captured screen into NV12 on the GPU and hands the result to a GPU encoder as a
/// texture. The picture never comes to the processor or into the app's memory: a whole new screen
/// costs well under a millisecond. Two small pixel shaders do it, one for brightness and one for
/// color, rendering straight into the two planes of the NV12 texture, with the same BT.709 video
/// range math as ColorConvert, which <see cref="Check"/> makes sure of on this PC's GPU. The
/// GPU's video processor could do the same, but it keeps some 25 MB of its own for it.
/// </summary>
internal sealed class GpuConverter : IDisposable
{
    private const int Pool = 4; // a GPU encoder may still read a frame or two while the next comes

    private readonly ID3D11Device _device;
    private readonly ID3D11DeviceContext _context;
    private readonly ID3D11VertexShader _fill;
    private readonly ID3D11PixelShader _luma, _chroma;
    private readonly ID3D11SamplerState _sampler;
    private readonly ID3D11RasterizerState _clip;
    private readonly ID3D11Buffer _params;
    private readonly ID3D11ShaderResourceView? _screen; // null when frames come one by one
    private readonly int _scale, _inWidth, _inHeight;
    private readonly ID3D11Texture2D[] _textures;
    private readonly ID3D11RenderTargetView[] _lumaViews, _chromaViews;
    private readonly bool _ownTextures;
    private readonly Viewport _lumaPort, _chromaPort;
    private int _next;

    public int Width { get; }
    public int Height { get; }

    /// <param name="context">The device's immediate context, owned by whoever made the device.</param>
    /// <param name="picture">
    /// The BGRA texture to convert, a new picture each time it changes; or null, when the frames
    /// come one by one to <see cref="Convert(ID3D11Texture2D, List{Dirty})"/> and only what changed
    /// is converted into the target, which then keeps the whole frame.
    /// </param>
    /// <param name="outWidth">The frame's width: the picture's, or half of it to send it at half size.</param>
    /// <param name="target">
    /// The one texture to convert into, an encoder's own, instead of a pool of this converter's. It
    /// may be larger than the frame, as encoders that want whole macroblocks have it: the frame
    /// goes in its top left corner and the rest stays black.
    /// </param>
    public unsafe GpuConverter(ID3D11Device device, ID3D11DeviceContext context, ID3D11Texture2D? picture,
        int inWidth, int inHeight, int outWidth, int outHeight, ID3D11Texture2D? target = null)
    {
        if (picture == null && target == null) throw new ArgumentException("frames that come one by one need a target that keeps them");
        Width = outWidth;
        Height = outHeight;
        _device = device;
        _context = context;
        (_inWidth, _inHeight) = (inWidth, inHeight);
        _scale = outWidth * 2 <= inWidth ? 2 : 1;
        float scale = _scale;
        try
        {
            _fill = device.CreateVertexShader(FillShader);
            _luma = device.CreatePixelShader(LumaShader);
            _chroma = device.CreatePixelShader(ChromaShader);
            _sampler = device.CreateSamplerState(new SamplerDescription(Filter.MinMagMipLinear, TextureAddressMode.Clamp));
            _clip = device.CreateRasterizerState(new RasterizerDescription(CullMode.None, FillMode.Solid) { ScissorEnable = true });
            var param = stackalloc float[] { 1f / inWidth, 1f / inHeight, scale, 0 };
            _params = device.CreateBuffer(new BufferDescription(16, BindFlags.ConstantBuffer, ResourceUsage.Immutable), new SubresourceData(param));
            if (picture != null) _screen = device.CreateShaderResourceView(picture);

            _ownTextures = target == null;
            _textures = target != null ? new[] { target } : new ID3D11Texture2D[Pool];
            _lumaViews = new ID3D11RenderTargetView[_textures.Length];
            _chromaViews = new ID3D11RenderTargetView[_textures.Length];
            for (int i = 0; i < _textures.Length; i++)
            {
                if (_ownTextures) _textures[i] = device.CreateTexture2D(new Texture2DDescription
                {
                    Width = (uint)outWidth,
                    Height = (uint)outHeight,
                    MipLevels = 1,
                    ArraySize = 1,
                    Format = Format.NV12,
                    SampleDescription = new SampleDescription(1, 0),
                    Usage = ResourceUsage.Default,
                    BindFlags = BindFlags.RenderTarget,
                });
                // A view of the brightness plane in R8, of the color plane in R8G8.
                _lumaViews[i] = device.CreateRenderTargetView(_textures[i], new RenderTargetViewDescription(_textures[i], RenderTargetViewDimension.Texture2D, Format.R8_UNorm));
                _chromaViews[i] = device.CreateRenderTargetView(_textures[i], new RenderTargetViewDescription(_textures[i], RenderTargetViewDimension.Texture2D, Format.R8G8_UNorm));
                // Black where the frame does not reach, in a target larger than the frame.
                _context.ClearRenderTargetView(_lumaViews[i], new Color4(16 / 255f, 0, 0, 0));
                _context.ClearRenderTargetView(_chromaViews[i], new Color4(128 / 255f, 128 / 255f, 0, 0));
            }
            _lumaPort = new Viewport(0, 0, outWidth, outHeight);
            _chromaPort = new Viewport(0, 0, outWidth / 2, outHeight / 2);
        }
        catch
        {
            Dispose();
            throw;
        }
    }

    /// <summary>
    /// Converts the picture as it is now into the next texture of the pool, and returns it. Fed
    /// frame by frame instead, returns the target as the frames left it.
    /// </summary>
    public ID3D11Texture2D Convert()
    {
        if (_screen == null) return _textures[0];
        int i = _next;
        _next = (_next + 1) % _textures.Length;
        Draw(_screen, i, null);
        return _textures[i];
    }

    /// <summary>
    /// Converts what changed in a frame, given in the frame's pixels, into the target: one pass
    /// per rectangle, clipped to it, or the whole frame when much changed.
    /// </summary>
    public void Convert(ID3D11Texture2D frame, List<Dirty> changed)
    {
        long area = 0;
        foreach (var d in changed) area += (long)d.W * d.H;
        using var view = _device.CreateShaderResourceView(frame);
        Draw(view, 0, changed.Count > 16 || area * 2 > (long)_inWidth * _inHeight ? null : changed);
    }

    private void Draw(ID3D11ShaderResourceView source, int i, List<Dirty>? rects)
    {
        var c = _context;
        c.IASetPrimitiveTopology(PrimitiveTopology.TriangleList);
        c.IASetInputLayout(null);
        c.VSSetShader(_fill);
        c.PSSetShaderResource(0, source);
        c.PSSetSampler(0, _sampler);
        c.PSSetConstantBuffer(0, _params);
        c.RSSetState(_clip);
        for (int plane = 0; plane < 2; plane++)
        {
            c.OMSetRenderTargets(plane == 0 ? _lumaViews[i] : _chromaViews[i]);
            c.RSSetViewport(plane == 0 ? _lumaPort : _chromaPort);
            c.PSSetShader(plane == 0 ? _luma : _chroma);
            int div = plane == 0 ? _scale : _scale * 2; // frame pixels per pixel of this plane
            if (rects == null)
            {
                c.RSSetScissorRect(0, 0, Width / (plane + 1), Height / (plane + 1));
                c.Draw(3, 0);
                continue;
            }
            foreach (var d in rects)
            {
                // Out to whole pixels of the color plane, so both planes cover the same.
                int a = _scale * 2;
                int x0 = d.X / a * a, y0 = d.Y / a * a;
                int x1 = (d.X + d.W + a - 1) / a * a, y1 = (d.Y + d.H + a - 1) / a * a;
                c.RSSetScissorRect(x0 / div, y0 / div, x1 / div, y1 / div);
                c.Draw(3, 0);
            }
        }
        // Nothing stays bound: the encoder reads the frame, the capture writes the picture.
        c.OMSetRenderTargets((ID3D11RenderTargetView)null!);
        c.PSSetShaderResource(0, null!);
    }
    /// <summary>
    /// Converts a small test picture on the GPU and with ColorConvert and compares the two. A GPU
    /// that filters or rounds its own way and comes out different is not used.
    /// Returns null when they agree, else what differs.
    /// </summary>
    public static unsafe string? Check(ID3D11Device device, ID3D11DeviceContext context)
    {
        const int w = 64, h = 32;
        // Blocks of 8 by 8 in one color each: grays from black to white, the primaries, and mixes.
        var colors = new (byte R, byte G, byte B)[32];
        for (int i = 0; i < 8; i++) colors[i] = ((byte)(i * 255 / 7), (byte)(i * 255 / 7), (byte)(i * 255 / 7));
        (byte, byte, byte)[] rest =
        {
            (255, 0, 0), (0, 255, 0), (0, 0, 255), (255, 255, 0), (0, 255, 255), (255, 0, 255), (128, 0, 0), (0, 128, 0),
            (0, 0, 128), (200, 120, 40), (40, 120, 200), (120, 200, 40), (250, 240, 230), (20, 30, 40), (90, 60, 160), (160, 90, 60),
            (255, 128, 0), (0, 128, 255), (128, 255, 0), (64, 64, 192), (192, 64, 64), (64, 192, 64), (230, 230, 250), (30, 30, 30),
        };
        rest.CopyTo(colors, 8);
        var bgra = new byte[w * h * 4];
        for (int y = 0; y < h; y++)
        for (int x = 0; x < w; x++)
        {
            int i = (y * w + x) * 4;
            var c = colors[(y / 8) * 8 + x / 8];
            (bgra[i + 2], bgra[i + 1], bgra[i], bgra[i + 3]) = (c.R, c.G, c.B, 255);
        }

        ID3D11Texture2D? source = null, staging = null;
        GpuConverter? converter = null;
        try
        {
            fixed (byte* p = bgra)
                source = device.CreateTexture2D(new Texture2DDescription
                {
                    Width = w, Height = h, MipLevels = 1, ArraySize = 1, Format = Format.B8G8R8A8_UNorm,
                    SampleDescription = new SampleDescription(1, 0), Usage = ResourceUsage.Default,
                    BindFlags = BindFlags.RenderTarget | BindFlags.ShaderResource,
                }, new SubresourceData((nint)p, w * 4));
            converter = new GpuConverter(device, context, source, w, h, w, h);
            var nv12 = converter.Convert();
            staging = device.CreateTexture2D(new Texture2DDescription
            {
                Width = w, Height = h, MipLevels = 1, ArraySize = 1, Format = Format.NV12,
                SampleDescription = new SampleDescription(1, 0), Usage = ResourceUsage.Staging,
                CPUAccessFlags = CpuAccessFlags.Read,
            });
            context.CopyResource(staging, nv12);
            var map = context.Map(staging, 0, MapMode.Read, Vortice.Direct3D11.MapFlags.None);
            using var cpu = new Nv12Frame(w, h);
            fixed (byte* p = bgra) ColorConvert.BgraToNv12(p, w * 4, 0, 0, w, h, cpu, 1);
            int worstY = 0, worstC = 0;
            try
            {
                byte* gpu = (byte*)map.DataPointer;
                int pitch = (int)map.RowPitch;
                for (int y = 0; y < h; y++)
                for (int x = 0; x < w; x++)
                    worstY = Math.Max(worstY, Math.Abs(gpu[y * pitch + x] - cpu.Data[y * w + x]));
                // Color only inside each block: GPUs blend color across neighbors in their own ways,
                // and only where the neighbors match must every way give the same.
                byte* uv = gpu + pitch * h;
                for (int y = 0; y < h / 2; y++)
                for (int x = 0; x < w / 2; x++)
                {
                    if (x % 4 is 0 or 3 || y % 4 is 0 or 3) continue;
                    for (int c = 0; c < 2; c++)
                        worstC = Math.Max(worstC, Math.Abs(uv[y * pitch + x * 2 + c] - cpu.UV[y * w + x * 2 + c]));
                }
            }
            finally { context.Unmap(staging, 0); }
            // A few levels apart is rounding; a different range or matrix is tens of levels off.
            return worstY <= 4 && worstC <= 6 ? null : $"the GPU's colors differ by {worstY} in brightness and {worstC} in color";
        }
        catch (Exception e) when (e is SharpGenException or NotSupportedException)
        {
            return e.Message;
        }
        finally
        {
            converter?.Dispose();
            staging?.Dispose();
            source?.Dispose();
        }
    }

    public void Dispose()
    {
        if (_lumaViews != null) foreach (var v in _lumaViews) v?.Dispose();
        if (_chromaViews != null) foreach (var v in _chromaViews) v?.Dispose();
        if (_ownTextures && _textures != null) foreach (var t in _textures) t?.Dispose();
        _screen?.Dispose();
        _params?.Dispose();
        _clip?.Dispose();
        _sampler?.Dispose();
        _chroma?.Dispose();
        _luma?.Dispose();
        _fill?.Dispose();
    }

